def city_country(city, country): 
    format = f"{city}, {country}"
    return format.title()

place_1 = city_country('Rome', 'Italy')
place_2 = city_country('Paris', 'France')
place_3 = city_country('Tokyo', 'Japan')

print(place_1)
print(place_2)
print(place_3)